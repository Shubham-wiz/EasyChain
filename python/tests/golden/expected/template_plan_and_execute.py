"""Plan and do (plan-and-execute)

A planner breaks the goal into a few steps, an agent carries out each step with its tools, and
the results are written up. The plan-and-execute pattern, made of ordinary steps you can change.

Generated by Easy Chain 0.4.0 from a version 1 flow spec.
It needs only LangChain and LangGraph:
`pip install -r requirements.txt`, then
`python plan_and_do_plan_and_execute.py '<inputs as JSON>'`.

The compiled graph is `graph`; call `build_graph(checkpointer=...)` to keep Save Points.
Code steps run in this process here. Easy Chain runs them in a sandbox (a
locked-down container); run this only with code you trust.
"""

import json
import os
import re
import sys
from typing import Annotated, Any

from langchain.agents import create_agent
from langchain.agents.middleware import ToolCallLimitMiddleware, ToolErrorMiddleware
from langchain.chat_models import init_chat_model
from langchain_core.exceptions import OutputParserException
from langchain_core.messages import AnyMessage, HumanMessage
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.tools import BaseTool, tool
from langgraph.graph import END, START, StateGraph
from langgraph.types import Send
from pydantic import BaseModel, Field, ValidationError
from typing_extensions import TypedDict

# ── Flow Data ────────────────────────────────────────────────────────────────


def collect_items(old: list[Any] | None, new: list[Any] | None) -> list[Any]:
    """Update rule for For Each results: None starts a new list, anything else is added."""
    if new is None:
        return []
    return (old or []) + new


class FlowData(TypedDict, total=False):
    """The named fields that steps read and write."""

    query: str  # What to look up, like "flight to Rome" or "hotel in Paris".
    goal: str  # What you want done
    each_step_results: Annotated[list[Any], collect_items]  # Results collected by “For each step” while it runs.
    each_step_index: float  # The item “For each step” is working on.
    prompt: list[AnyMessage]
    plan: dict[str, Any]
    steps: list[Any]
    task: Any
    results: list[Any]
    result: str
    answer: str


class FlowInput(TypedDict, total=False):
    """What a run takes."""

    goal: str  # What you want done


class FlowOutput(TypedDict, total=False):
    """What a run returns."""

    answer: str
    steps: list[Any]
    results: list[Any]


# ── Helpers ──────────────────────────────────────────────────────────────────


def fill(template: str, data: dict[str, Any]) -> str:
    """Put Flow Data values into {field} and environment variables into {secret:NAME}."""

    def value(match: re.Match[str]) -> str:
        name = match.group(1)
        if name.startswith("secret:"):
            return os.environ.get(name.removeprefix("secret:"), "")
        found = data.get(name)
        return "" if found is None else str(found)

    return re.sub(r"\{((?:secret:)?[A-Za-z_][A-Za-z0-9_]*)\}", value, template)


def as_text(value: Any) -> str:
    """Put a list or object into a prompt as readable text (one list item per paragraph)."""
    if value is None:
        return ""
    if isinstance(value, list):
        return "\n\n".join(as_text(item) for item in value)
    if isinstance(value, dict):
        return json.dumps(value, indent=2, ensure_ascii=False, default=str)
    return str(value)


def tell_agent(error: Exception, request: Any) -> str:
    """When a tool fails, tell the agent (so it can try another way) instead of stopping."""
    return f"The tool failed ({type(error).__name__}): {error}"


# ── Steps ────────────────────────────────────────────────────────────────────


plan_prompt_template = ChatPromptTemplate.from_messages(
    [
        ("system", "You plan work for an assistant that can look up flight and hotel prices. Break the goal into two to five short steps, in order; each step is one thing to look up or work out."),
        ("human", "{goal}"),
    ]
)


def plan_prompt(data: FlowData) -> dict[str, Any]:
    """Instructions · Ask for a plan

    Fills in {goal} and saves the prompt messages as `prompt`.
    """
    prompt = plan_prompt_template.invoke({"goal": data.get("goal", "")})
    return {"prompt": prompt.to_messages()}


class PlannerReply(BaseModel):
    """The plan."""

    steps: list[str] = Field(description="The steps, in order, each a short sentence.")


def planner(data: FlowData) -> dict[str, Any]:
    """AI Model · Planner

    Sends `prompt` to openai:gpt-4o-mini and saves the reply, in the PlannerReply format, as
    `plan`. Each field is also saved on its own: `steps`.
    """
    model = init_chat_model("openai:gpt-4o-mini")
    structured = model.with_structured_output(PlannerReply).with_retry(
        retry_if_exception_type=(ValidationError, OutputParserException),
        stop_after_attempt=2,
    )
    reply = structured.invoke(data["prompt"])
    if reply is None:
        raise ValueError("The model didn't reply in the PlannerReply format.")
    result = reply.model_dump()
    return {"plan": result, "steps": result["steps"]}


def each_step(data: FlowData) -> dict[str, Any]:
    """For Each · For each step

    Starts a new list of results; send_each_step below sends each item of `steps` to `do_step`.
    """
    return {"each_step_results": None}  # None starts the list again


def send_each_step(data: FlowData) -> list[Send] | str:
    """Send the next 1 items of `steps` to their own runs of the step (they run side by side); the
    next 1 go once those are done.
    """
    items = data.get("steps")
    if items is None:
        items = []
    elif not isinstance(items, list):
        items = [items]
    start = len(data.get("each_step_results") or [])  # how many are done
    if start >= len(items):
        return "each_step__done"
    return [
        Send("do_step", {**data, "task": item, "each_step_index": number})
        for number, item in enumerate(items[start : start + 1], start)
    ]


def do_step_for_each_step(data: FlowData) -> dict[str, Any]:
    """Run `do_step` for one item of “For each step” and keep `result`."""
    result = do_step(data) or {}
    return {"each_step_results": [(data["each_step_index"], result.get("result"))]}


def each_step_next(data: FlowData) -> dict[str, Any]:
    """Wait until the items send_each_step sent are done; then send_each_step sends the next."""
    return {}


def each_step_done(data: FlowData) -> dict[str, Any]:
    """Put the results of “For each step” in item order and save them as `results`."""
    collected = sorted(data.get("each_step_results") or [], key=lambda pair: pair[0])
    return {"results": [result for _, result in collected]}


DO_STEP_INSTRUCTIONS = "You carry out one step of a plan for this goal: {goal}. Use your tool to look things up, and reply with what you found in one or two sentences."


# Code · Find prices (sets prices)
PRICES = {
    ("flight", "rome"): "A flight to Rome costs 89 euros.",
    ("flight", "paris"): "A flight to Paris costs 112 euros.",
    ("hotel", "rome"): "A hotel in Rome costs 95 euros a night.",
    ("hotel", "paris"): "A hotel in Paris costs 120 euros a night.",
}


def find_prices(data):
    """Return the prices that match what was asked."""
    asked = str(data["query"]).lower()
    found = [text for (kind, city), text in PRICES.items() if kind in asked and city in asked]
    if not found:
        found = [text for (kind, city), text in PRICES.items() if city in asked]
    return {"prices": " ".join(found) or "No prices found for that."}


def find_prices_tool(data: FlowData) -> BaseTool:
    """Code “Find prices” as a tool for agents: find_prices(query)."""

    @tool(
        "find_prices",
        description="Finds the price of a flight to a city, or of a hotel night in a city.",
    )
    def run_tool(
        query: Annotated[str, "What to look up, like \"flight to Rome\" or \"hotel in Paris\"."],
    ) -> str:
        result = find_prices({**data, "query": query})
        return as_text(result.get("prices"))

    return run_tool


def do_step(data: FlowData) -> dict[str, Any]:
    """Agent · Do the step

    Works on `task` using openai:gpt-4o-mini and the tool find_prices, and saves its answer as
    `result`.
    """
    agent = create_agent(
        model=init_chat_model("openai:gpt-4o-mini"),
        tools=[find_prices_tool(data)],
        system_prompt=fill(DO_STEP_INSTRUCTIONS, data),
        middleware=[
            ToolCallLimitMiddleware(run_limit=3),
            ToolErrorMiddleware(tell_agent),
        ],
        name="do_step",
    )
    result = agent.invoke(
        {"messages": [HumanMessage(str(data.get("task", "")))]}, {"recursion_limit": 20}
    )
    return {"result": result["messages"][-1].text}


WRITE_PROMPT_MESSAGE = """\
Goal: {goal}

What each step found:
{results}

Answer the goal in a few sentences, with the numbers."""

write_prompt_template = ChatPromptTemplate.from_messages(
    [
        ("system", "You write short, clear answers from the results of a plan."),
        ("human", WRITE_PROMPT_MESSAGE),
    ]
)


def write_prompt(data: FlowData) -> dict[str, Any]:
    """Instructions · Write it up

    Fills in {goal}, {results} and saves the prompt messages as `prompt`.
    """
    prompt = write_prompt_template.invoke(
        {
            "goal": data.get("goal", ""),
            "results": as_text(data.get("results")),
        }
    )
    return {"prompt": prompt.to_messages()}


def write_up(data: FlowData) -> dict[str, Any]:
    """AI Model · Answer

    Sends `prompt` to openai:gpt-4o-mini and saves the reply as `answer`.
    """
    model = init_chat_model("openai:gpt-4o-mini")
    reply = model.invoke(data["prompt"])
    return {"answer": reply.text}


# ── Flow ─────────────────────────────────────────────────────────────────────


def build_graph(checkpointer=None, *, store=None, cache=None):
    """Wire the steps into a LangGraph graph.

    Pass a checkpointer (for example InMemorySaver()) to keep a Save Point after every step,
    a store to remember side effects across retries, and a cache for cached steps.
    """
    builder = StateGraph(FlowData, input_schema=FlowInput, output_schema=FlowOutput)

    builder.add_node("plan_prompt", plan_prompt)
    builder.add_node("planner", planner)
    builder.add_node("each_step", each_step)
    builder.add_node("each_step__next", each_step_next)
    builder.add_node("each_step__done", each_step_done, defer=True)
    builder.add_node("do_step", do_step_for_each_step)
    builder.add_node("write_prompt", write_prompt)
    builder.add_node("write_up", write_up)

    builder.add_edge(START, "plan_prompt")
    builder.add_edge("plan_prompt", "planner")
    builder.add_edge("planner", "each_step")
    builder.add_conditional_edges("each_step", send_each_step, ["do_step", "each_step__done"])
    builder.add_conditional_edges("each_step__next", send_each_step, ["do_step", "each_step__done"])
    builder.add_edge("each_step__done", "write_prompt")
    builder.add_edge("do_step", "each_step__next")
    builder.add_edge("write_prompt", "write_up")
    builder.add_edge("write_up", END)
    return builder.compile(checkpointer=checkpointer, store=store, cache=cache)


graph = build_graph()


if __name__ == "__main__":
    example = {
        "goal": "Compare the cost of three nights in Rome and in Paris, flights included.",
    }
    inputs = json.loads(sys.argv[1]) if len(sys.argv) > 1 else example
    result = graph.invoke(inputs)
    print(json.dumps(result, indent=2, ensure_ascii=False, default=str))
