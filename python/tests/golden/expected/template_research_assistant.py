"""Research assistant

Ask a question and give it a few pages to read. A Deep Agent plans the work, has its researcher
read the pages and take notes with sources, writes a short report with sources to /report.md,
and has its reviewer check the report before it answers.

Generated by Easy Chain 0.4.0 from a version 1 flow spec.
It needs LangChain, LangGraph and deepagents:
`pip install -r requirements.txt`, then
`python research_assistant.py '<inputs as JSON>'`.

The compiled graph is `graph`; call `build_graph(checkpointer=...)` to keep Save Points.
"""

import json
import re
import sys
from html.parser import HTMLParser
from typing import Annotated, Any

import httpx
from deepagents import FilesystemMiddleware, FsToolName, SubAgent, create_deep_agent
from deepagents.backends.utils import create_file_data, file_data_to_string
from deepagents.middleware.subagents import GENERAL_PURPOSE_SUBAGENT
from langchain.agents.middleware import (
    TodoListMiddleware,
    ToolCallLimitMiddleware,
    ToolErrorMiddleware,
)
from langchain.chat_models import init_chat_model
from langchain_core.messages import HumanMessage
from langchain_core.tools import BaseTool, tool
from langgraph.graph import END, START, StateGraph
from typing_extensions import TypedDict

# ── Flow Data ────────────────────────────────────────────────────────────────


class FlowData(TypedDict, total=False):
    """The named fields that steps read and write."""

    url: str  # The address of the web page to read, starting with http:// or https://
    request: str  # What to find out, and the addresses of the pages to read (one per line)
    answer: str
    files: dict[str, Any]
    plan: list[Any]


class FlowInput(TypedDict, total=False):
    """What a run takes."""

    request: str  # What to find out, and the addresses of the pages to read (one per line)


class FlowOutput(TypedDict, total=False):
    """What a run returns."""

    answer: str
    files: dict[str, Any]
    plan: list[Any]


# ── Helpers ──────────────────────────────────────────────────────────────────


# A Deep Agent's file tools: every one except `execute`. The files live in the run's
# state (saved with each Save Point), where there is no shell to run commands in.
FILE_TOOLS: list[FsToolName] = [
    "ls",
    "read_file",
    "write_file",
    "edit_file",
    "delete",
    "glob",
    "grep",
]


class _TextExtractor(HTMLParser):
    """Collects the visible text of an HTML page."""

    SKIP = {"script", "style", "noscript", "head", "svg", "template"}
    BLOCK = {
        "p", "div", "br", "li", "tr", "h1", "h2", "h3", "h4", "h5", "h6",
        "section", "article", "header", "footer", "pre", "blockquote",
    }

    def __init__(self) -> None:
        super().__init__()
        self.parts: list[str] = []
        self.skipping = 0

    def handle_starttag(self, tag: str, attrs: list) -> None:
        if tag in self.SKIP:
            self.skipping += 1
        elif tag in self.BLOCK:
            self.parts.append("\n")

    def handle_endtag(self, tag: str) -> None:
        if tag in self.SKIP and self.skipping:
            self.skipping -= 1
        elif tag in self.BLOCK:
            self.parts.append("\n")

    def handle_data(self, text: str) -> None:
        if not self.skipping:
            self.parts.append(text)


def readable_text(page: str) -> str:
    """Turn an HTML page into the plain text a person would read."""
    if "<" not in page:
        return page.strip()
    parser = _TextExtractor()
    parser.feed(page)
    lines = (re.sub(r"\s+", " ", line).strip() for line in "".join(parser.parts).splitlines())
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip()


def as_text(value: Any) -> str:
    """Put a list or object into a prompt as readable text (one list item per paragraph)."""
    if value is None:
        return ""
    if isinstance(value, list):
        return "\n\n".join(as_text(item) for item in value)
    if isinstance(value, dict):
        return json.dumps(value, indent=2, ensure_ascii=False, default=str)
    return str(value)


def tell_agent(error: Exception, request: Any) -> str:
    """When a tool fails, tell the agent (so it can try another way) instead of stopping."""
    return f"The tool failed ({type(error).__name__}): {error}"


def general_helper(
    model: Any, tools: list[Any], middleware: list[Any], skills: list[str] | None = None
) -> SubAgent:
    """deepagents' general-purpose helper, with the Deep Agent's own tools, add-ons and
    skills, so the approvals and limits that apply to the Deep Agent apply to it too."""
    helper: SubAgent = {
        **GENERAL_PURPOSE_SUBAGENT,
        "model": model,
        "tools": tools,
        "middleware": [FilesystemMiddleware(tools=FILE_TOOLS), *middleware],
    }
    if skills:
        helper["skills"] = skills
    return helper


def agent_files(files: Any, skills: dict[str, str] | None = None) -> dict[str, Any]:
    """Flow Data files ({path: text}), and the skills' files, as a Deep Agent's file area."""
    found = dict(files) if isinstance(files, dict) else {}
    found.update(skills or {})
    return {str(path): create_file_data(str(text)) for path, text in found.items()}


def flow_files(files: Any) -> dict[str, str]:
    """A Deep Agent's file area as Flow Data: {path: text}, by path. Skills come from the
    flow each time, and large tool results are the agent's own scratch, so they stay out."""
    if not isinstance(files, dict):
        return {}
    return {
        path: file_data_to_string(data)
        for path, data in sorted(files.items())
        if data and not path.startswith(("/skills/", "/large_tool_results/"))
    }


# ── Steps ────────────────────────────────────────────────────────────────────


LEAD_INSTRUCTIONS = """\
You research questions for a busy reader and write short, accurate reports.

1. Plan the work as a to-do list, and keep it up to date.
2. Hand the reading to the researcher: the question, and the addresses of the pages to read. Only use the pages the person gave you.
3. Write the report to /report.md, following your research-report skill, using only the researcher's notes. Keep the notes in /notes.md.
4. Hand the report and the notes to the reviewer, and fix what the reviewer finds.
5. Answer with the report's two-sentence summary, and say the report is in /report.md.

If the pages don't answer part of the question, say so in the report; don't guess."""


RESEARCHER_INSTRUCTIONS = "You read web pages and take notes for a research report. Read each address you are given with read_page, follow your source-notes skill, and reply with the notes. Never add a fact the pages don't say."


def read_page(data: FlowData) -> dict[str, Any]:
    """Web request · Read a page

    GET {url} and save the page text as `page`.
    """
    response = httpx.request(
        "GET",
        data["url"],
        headers={"User-Agent": "Mozilla/5.0 (compatible; EasyChain/0.1)"},
        timeout=30,
        follow_redirects=True,
    )
    response.raise_for_status()
    return {"page": readable_text(response.text)[:20000]}


def read_page_tool(data: FlowData) -> BaseTool:
    """Web request “Read a page” as a tool for agents: read_page(url)."""

    @tool("read_page", description="Reads the web page at an address and returns its text.")
    def run_tool(
        url: Annotated[str, "The address of the web page to read, starting with http:// or https://"],
    ) -> str:
        result = read_page({**data, "url": url})
        return as_text(result.get("page"))

    return run_tool


def researcher_helper(data: FlowData) -> SubAgent:
    """Helper · Researcher

    A sub-agent of `lead`: it gets tasks from it, works on them with the tool read_page, and
    replies using openai:gpt-4o-mini.
    """
    return {
        "name": "researcher",
        "description": "Reads web pages and takes notes with their sources. Give it the question and the addresses of the pages to read.",
        "system_prompt": RESEARCHER_INSTRUCTIONS,
        "model": init_chat_model("openai:gpt-4o-mini"),
        "tools": [read_page_tool(data)],
        "middleware": [
            FilesystemMiddleware(tools=FILE_TOOLS),
            ToolCallLimitMiddleware(run_limit=8),
            ToolErrorMiddleware(tell_agent),
        ],
        "skills": ["/skills/researcher/"],
    }


REVIEWER_INSTRUCTIONS = "You check research reports. Compare the report with the notes you are given. List each fact in the report that the notes don't support, and each fact without a source number. If there is nothing to fix, reply with OK."


def reviewer_helper(data: FlowData) -> SubAgent:
    """Helper · Reviewer

    A sub-agent of `lead`: it gets tasks from it, and replies using openai:gpt-4o-mini.
    """
    return {
        "name": "reviewer",
        "description": "Checks a draft report against the notes. Give it the report and the notes; it replies with what to fix, or OK.",
        "system_prompt": REVIEWER_INSTRUCTIONS,
        "model": init_chat_model("openai:gpt-4o-mini"),
        "tools": [],
        "middleware": [
            FilesystemMiddleware(tools=FILE_TOOLS),
            ToolErrorMiddleware(tell_agent),
        ],
    }


# The skills (from the Skills library) of “Research lead” and its Helpers, in their files.
