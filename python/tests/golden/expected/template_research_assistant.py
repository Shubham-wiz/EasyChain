def lead(data: FlowData) -> dict[str, Any]:
    """Deep Agent · Research lead

    Works on `request` using openai:gpt-4o-mini, hands tasks to the Helpers researcher and
    reviewer, keeps its files in `files`, and saves its answer as `answer`.
    """
    model = init_chat_model("openai:gpt-4o-mini")
    tools: list[BaseTool] = []
    addons = [
        ToolErrorMiddleware(tell_agent),
    ]
    agent = create_deep_agent(
        model=model,
        tools=tools,
        system_prompt=LEAD_INSTRUCTIONS,
        middleware=[TodoListMiddleware(), FilesystemMiddleware(tools=FILE_TOOLS), *addons],
        skills=["/skills/lead/"],
        subagents=[
            general_helper(model, tools, addons, ["/skills/lead/"]),
            researcher_helper(data),
            reviewer_helper(data),
        ],
        name="lead",
    )
    result = agent.invoke(
        {
            "messages": [HumanMessage(str(data.get("request", "")))],
            "files": agent_files(data.get("files"), LEAD_SKILLS),
        },
        {"recursion_limit": 500},
    )
    return {
        "answer": result["messages"][-1].text,
        "files": flow_files(result.get("files")),
        "plan": result.get("todos") or [],
    }


# ── Flow ─────────────────────────────────────────────────────────────────────


def build_graph(checkpointer=None, *, store=None, cache=None):
    """Wire the steps into a LangGraph graph.

    Pass a checkpointer (for example InMemorySaver()) to keep a Save Point after every step,
    a store to remember side effects across retries, and a cache for cached steps.
    """
    builder = StateGraph(FlowData, input_schema=FlowInput, output_schema=FlowOutput)

    builder.add_node("lead", lead)

    builder.add_edge(START, "lead")
    builder.add_edge("lead", END)
    return builder.compile(checkpointer=checkpointer, store=store, cache=cache)


graph = build_graph()


if __name__ == "__main__":
    example = {
        "request": """\
How do honey bees live and work together?
https://en.wikipedia.org/wiki/Honey_bee
https://en.wikipedia.org/wiki/Beehive""",
    }
    inputs = json.loads(sys.argv[1]) if len(sys.argv) > 1 else example
    result = graph.invoke(inputs)
    print(json.dumps(result, indent=2, ensure_ascii=False, default=str))
