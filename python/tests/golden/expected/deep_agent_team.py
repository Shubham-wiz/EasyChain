# ── Flow Data ────────────────────────────────────────────────────────────────


class FlowData(TypedDict, total=False):
    """The named fields that steps read and write."""

    page_url: str  # The address of a page to read.
    topic: str
    audience: str
    answer: str
    files: dict[str, Any]
    plan: list[Any]


class FlowInput(TypedDict, total=False):
    """What a run takes."""

    topic: str
    audience: str


class FlowOutput(TypedDict, total=False):
    """What a run returns."""

    answer: str
    files: dict[str, Any]
    plan: list[Any]


# ── Helpers ──────────────────────────────────────────────────────────────────


# A Deep Agent's file tools: every one except `execute`. The files live in the run's
# state (saved with each Save Point), where there is no shell to run commands in.
FILE_TOOLS: list[FsToolName] = [
    "ls",
    "read_file",
    "write_file",
    "edit_file",
    "delete",
    "glob",
    "grep",
]


def fill(template: str, data: dict[str, Any]) -> str:
    """Put Flow Data values into {field} and environment variables into {secret:NAME}."""

    def value(match: re.Match[str]) -> str:
        name = match.group(1)
        if name.startswith("secret:"):
            return os.environ.get(name.removeprefix("secret:"), "")
        found = data.get(name)
        return "" if found is None else str(found)

    return re.sub(r"\{((?:secret:)?[A-Za-z_][A-Za-z0-9_]*)\}", value, template)


class _TextExtractor(HTMLParser):
    """Collects the visible text of an HTML page."""

    SKIP = {"script", "style", "noscript", "head", "svg", "template"}
    BLOCK = {
        "p", "div", "br", "li", "tr", "h1", "h2", "h3", "h4", "h5", "h6",
        "section", "article", "header", "footer", "pre", "blockquote",
    }

    def __init__(self) -> None:
        super().__init__()
        self.parts: list[str] = []
        self.skipping = 0

    def handle_starttag(self, tag: str, attrs: list) -> None:
        if tag in self.SKIP:
            self.skipping += 1
        elif tag in self.BLOCK:
            self.parts.append("\n")

    def handle_endtag(self, tag: str) -> None:
        if tag in self.SKIP and self.skipping:
            self.skipping -= 1
        elif tag in self.BLOCK:
            self.parts.append("\n")

    def handle_data(self, text: str) -> None:
        if not self.skipping:
            self.parts.append(text)


def readable_text(page: str) -> str:
    """Turn an HTML page into the plain text a person would read."""
    if "<" not in page:
        return page.strip()
    parser = _TextExtractor()
    parser.feed(page)
    lines = (re.sub(r"\s+", " ", line).strip() for line in "".join(parser.parts).splitlines())
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip()


def as_text(value: Any) -> str:
    """Put a list or object into a prompt as readable text (one list item per paragraph)."""
    if value is None:
        return ""
    if isinstance(value, list):
        return "\n\n".join(as_text(item) for item in value)
    if isinstance(value, dict):
        return json.dumps(value, indent=2, ensure_ascii=False, default=str)
    return str(value)


def tell_agent(error: Exception, request: Any) -> str:
    """When a tool fails, tell the agent (so it can try another way) instead of stopping."""
    return f"The tool failed ({type(error).__name__}): {error}"


def general_helper(
    model: Any, tools: list[Any], middleware: list[Any], skills: list[str] | None = None
) -> SubAgent:
    """deepagents' general-purpose helper, with the Deep Agent's own tools, add-ons and
    skills, so the approvals and limits that apply to the Deep Agent apply to it too."""
    helper: SubAgent = {
        **GENERAL_PURPOSE_SUBAGENT,
        "model": model,
        "tools": tools,
        "middleware": [FilesystemMiddleware(tools=FILE_TOOLS), *middleware],
    }
    if skills:
        helper["skills"] = skills
    return helper


def agent_files(files: Any, skills: dict[str, str] | None = None) -> dict[str, Any]:
    """Flow Data files ({path: text}), and the skills' files, as a Deep Agent's file area."""
    found = dict(files) if isinstance(files, dict) else {}
    found.update(skills or {})
    return {str(path): create_file_data(str(text)) for path, text in found.items()}


def flow_files(files: Any) -> dict[str, str]:
    """A Deep Agent's file area as Flow Data: {path: text}, by path. Skills come from the
    flow each time, and large tool results are the agent's own scratch, so they stay out."""
    if not isinstance(files, dict):
        return {}
    return {
        path: file_data_to_string(data)
        for path, data in sorted(files.items())
        if data and not path.startswith(("/skills/", "/large_tool_results/"))
    }


def ask_in_terminal(request: dict[str, Any]) -> dict[str, Any]:
    """Answer an Ask a Human step in the terminal (Easy Chain's Inbox does this in the app)."""
    if "action_requests" in request:
        # An agent wants to use a tool that needs approval (HumanInTheLoopMiddleware).
        decisions = []
        for action in request["action_requests"]:
            print(f"\nThe agent wants to use {action['name']} with {action['args']}")
            if input("approve? [y/n]> ").strip().lower().startswith("y"):
                decisions.append({"type": "approve"})
            else:
                decisions.append({"type": "reject", "message": input("why not?> ")})
        return {"decisions": decisions}
    print(f"\n{request['question']}")
    for name, value in request.get("show", {}).items():
        print(f"  {name}: {value}")
    kind = request.get("kind", "approve")
    if kind == "answer":
        return {"action": "approve", "value": input("answer> ")}
    if kind == "choose":
        options = request.get("options", [])
        for number, option in enumerate(options, start=1):
            print(f"  {number}. {option}")
        while True:
            picked = input("choose a number> ").strip()
            if picked.isdigit() and 1 <= int(picked) <= len(options):
                return {"action": "approve", "value": options[int(picked) - 1]}
            print(f"Type a number from 1 to {len(options)}.")
    approved = input("approve? [y/n]> ").strip().lower().startswith("y")
    answer: dict[str, Any] = {"action": "approve" if approved else "reject", "comment": input("comment> ")}
    if kind == "edit" and approved:
        edited = input(f"new {request.get('field')} (leave empty to keep it)> ")
        if edited:
            answer["value"] = edited
    return answer


# ── Steps ────────────────────────────────────────────────────────────────────


LEAD_INSTRUCTIONS = """\
You research a topic for {audience} and write a report to /report.md.
Plan the work first. Ask the researcher for facts and the editor for a review."""


def read_page(data: FlowData) -> dict[str, Any]:
    """Web request · Read a page

    GET {page_url} and save the page text as `page_text`.
    """
    response = httpx.request(
        "GET",
        data["page_url"],
        headers={"User-Agent": "Mozilla/5.0 (compatible; EasyChain/0.1)"},
        timeout=30,
        follow_redirects=True,
    )
    response.raise_for_status()
    return {"page_text": readable_text(response.text)[:20000]}


def read_page_tool(data: FlowData) -> BaseTool:
    """Web request “Read a page” as a tool for agents: read_page(page_url)."""

    @tool("read_page", description="Reads a web page and returns its text.")
    def run_tool(page_url: Annotated[str, "The address of a page to read."]) -> str:
        result = read_page({**data, "page_url": page_url})
        return as_text(result.get("page_text"))

    return run_tool


RESEARCHER_INSTRUCTIONS = "Find facts for {audience}. Reply with short notes and the pages you used."


# Code · Search the web (sets results)
def web_search(data):
    """Return search results for a query."""
    return {"results": [f"https://example.com/{data['query'].replace(' ', '-')}"]}


def web_search_tool(data: FlowData) -> BaseTool:
    """Code “Search the web” as a tool for agents: web_search(query)."""

    @tool(
        "web_search",
        description="Searches the web (a stand-in that returns a fixed result).",
    )
    def run_tool(query: str) -> str:
        result = web_search({**data, "query": query})
        return as_text(result.get("results"))

    return run_tool


def researcher_helper(data: FlowData) -> SubAgent:
    """Helper · Researcher

    A sub-agent of `lead`: it gets tasks from it, works on them with the tools read_page and
    web_search, and replies using openai:gpt-4o-mini.
    """
    return {
        "name": "researcher",
        "description": "Finds facts about a topic and replies with short notes and their sources.",
        "system_prompt": fill(RESEARCHER_INSTRUCTIONS, data),
        "model": init_chat_model("openai:gpt-4o-mini"),
        "tools": [read_page_tool(data), web_search_tool(data)],
        "middleware": [
            FilesystemMiddleware(tools=FILE_TOOLS),
            ToolErrorMiddleware(tell_agent),
            ToolRetryMiddleware(max_retries=1, on_failure="error"),
        ],
        "skills": ["/skills/researcher/"],
    }


EDITOR_INSTRUCTIONS = "Read the draft and reply with the three most useful changes."


def editor_helper(data: FlowData) -> SubAgent:
    """Helper · Editor

    A sub-agent of `lead`: it gets tasks from it, and replies using anthropic:claude-haiku-4-5.
    """
    return {
        "name": "editor",
        "description": "Reviews a draft in the files and suggests changes.",
        "system_prompt": EDITOR_INSTRUCTIONS,
        "model": init_chat_model("anthropic:claude-haiku-4-5", temperature=0.2),
        "tools": [],
        "middleware": [
            FilesystemMiddleware(tools=FILE_TOOLS),
            ToolErrorMiddleware(tell_agent),
        ],
    }


