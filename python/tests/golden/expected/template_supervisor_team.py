"""Support team (supervisor)

A supervisor hands the customer's request to the right specialist, one after another, until
their notes cover it, then the reply is written from the notes. The supervisor pattern, made of
ordinary steps you can change.

Generated by Easy Chain 0.5.0 from a version 1 flow spec.
It needs only LangChain and LangGraph:
`pip install -r requirements.txt`, then
`python support_team_supervisor.py '<inputs as JSON>'`.

The compiled graph is `graph`; call `build_graph(checkpointer=...)` to keep Save Points.
Code steps run in this process here. Easy Chain runs them in a sandbox (a
locked-down container); run this only with code you trust.
"""

import json
import os
import re
import sys
from typing import Any

from langchain.agents import create_agent
from langchain.agents.middleware import ToolCallLimitMiddleware, ToolErrorMiddleware
from langchain.chat_models import init_chat_model
from langchain_core.messages import AnyMessage, HumanMessage
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.tools import BaseTool, tool
from langgraph.graph import END, START, StateGraph
from typing_extensions import TypedDict

# ── Flow Data ────────────────────────────────────────────────────────────────


class FlowData(TypedDict, total=False):
    """The named fields that steps read and write."""

    request: str  # The customer's message
    supervisor_rounds: float  # How many times “Supervisor” has run in this run.
    next_specialist: str
    billing_note: str
    technical_note: str
    accounts_note: str
    prompt: list[AnyMessage]
    answer: str


class FlowInput(TypedDict, total=False):
    """What a run takes."""

    request: str  # The customer's message
    supervisor_rounds: float  # How many times “Supervisor” has run in this run.


class FlowOutput(TypedDict, total=False):
    """What a run returns."""

    answer: str
    billing_note: str
    technical_note: str
    accounts_note: str


# Loop round counters; every new run starts them again.
ROUND_COUNTERS: dict[str, Any] = {"supervisor_rounds": 0}


# ── Helpers ──────────────────────────────────────────────────────────────────


def pick_exit(reply: str, exits: list[str], otherwise: str) -> str:
    """Match an AI reply to one of a Decision's exit names.

    The reply must be an exit name, or start with one ("Refund, because ..."), ignoring case,
    spaces and punctuation. Longer names are tried first, so "No refund" isn't taken for "No".
    Anything else ("None of the above", "Not a complaint") takes the otherwise exit.
    """
    said = re.findall(r"\w+", reply.lower())
    for name in sorted(exits, key=lambda name: -len(re.findall(r"\w+", name))):
        words = re.findall(r"\w+", name.lower())
        if reply.strip().lower() == name.strip().lower() or (
            words and said[: len(words)] == words
        ):
            return name
    return otherwise


def fill(template: str, data: dict[str, Any]) -> str:
    """Put Flow Data values into {field} and environment variables into {secret:NAME}."""

    def value(match: re.Match[str]) -> str:
        name = match.group(1)
        if name.startswith("secret:"):
            return os.environ.get(name.removeprefix("secret:"), "")
        found = data.get(name)
        return "" if found is None else str(found)

    return re.sub(r"\{((?:secret:)?[A-Za-z_][A-Za-z0-9_]*)\}", value, template)


def as_text(value: Any) -> str:
    """Put a list or object into a prompt as readable text (one list item per paragraph)."""
    if value is None:
        return ""
    if isinstance(value, list):
        return "\n\n".join(as_text(item) for item in value)
    if isinstance(value, dict):
        return json.dumps(value, indent=2, ensure_ascii=False, default=str)
    return str(value)


def tell_agent(error: Exception, request: Any) -> str:
    """When a tool fails, tell the agent (so it can try another way) instead of stopping."""
    return f"The tool failed ({type(error).__name__}): {error}"


# ── Steps ────────────────────────────────────────────────────────────────────


SUPERVISOR_EXITS = ["Billing", "Technical", "Accounts"]
SUPERVISOR_GUIDANCE = """\
You lead a customer support team. Pick the specialist who should work on the customer's request next. Pick Finish when the notes below cover everything the customer asked.

Billing notes: {billing_note}
Technical notes: {technical_note}
Accounts notes: {accounts_note}
Choose the exit that fits best. Reply with the exit name only.

Exits:
- Billing: invoices, payments, charges, refunds and prices
- Technical: errors, crashes, bugs, slow pages and how to use the app
- Accounts: signing in, passwords, users and permissions
- Finish: none of the above"""


def supervisor(data: FlowData) -> dict[str, Any]:
    """Decision · Supervisor

    Asks openai:gpt-4o-mini which exit fits `request` and saves it as `next_specialist`.
    """
    model = init_chat_model("openai:gpt-4o-mini", temperature=0)
    reply = model.invoke([("system", fill(SUPERVISOR_GUIDANCE, data)), ("human", str(data.get("request", "")))])
    return {"next_specialist": pick_exit(reply.text, SUPERVISOR_EXITS, "Finish"), "supervisor_rounds": data.get("supervisor_rounds", 0) + 1}


def route_supervisor(data: FlowData) -> str:
    """Follow the exit the AI picked for "Supervisor"."""
    if data.get("supervisor_rounds", 0) >= 4:  # round limit reached
        return "Finish"
    return data.get("next_specialist") or "Finish"


BILLING_INSTRUCTIONS = "You are the billing specialist of a support team. Look up the customer's invoices, then write two or three short notes for the team about what you found and what you did. Don't write to the customer."


# Code · Find invoices (sets invoices)
INVOICES = [
    {"invoice": "1042", "date": "2026-05-03", "amount": 20.0, "paid": 2},
    {"invoice": "0977", "date": "2026-04-03", "amount": 20.0, "paid": 1},
]


def find_invoices(data):
    """Return the customer's recent invoices and how often each was paid."""
    return {"invoices": INVOICES}


def find_invoices_tool(data: FlowData) -> BaseTool:
    """Code “Find invoices” as a tool for agents: find_invoices()."""

    @tool("find_invoices", description="Finds the customer's recent invoices and payments.")
    def run_tool() -> str:
        result = find_invoices(data)
        return as_text(result.get("invoices"))

    return run_tool


def billing(data: FlowData) -> dict[str, Any]:
    """Agent · Billing specialist

    Works on `request` using openai:gpt-4o-mini and the tool find_invoices, and saves its answer
    as `billing_note`.
    """
    agent = create_agent(
        model=init_chat_model("openai:gpt-4o-mini"),
        tools=[find_invoices_tool(data)],
        system_prompt=BILLING_INSTRUCTIONS,
        middleware=[
            ToolCallLimitMiddleware(run_limit=3),
            ToolErrorMiddleware(tell_agent),
        ],
        name="billing",
    )
    result = agent.invoke(
        {"messages": [HumanMessage(str(data.get("request", "")))]}, {"recursion_limit": 20}
    )
    return {"billing_note": result["messages"][-1].text}


TECHNICAL_INSTRUCTIONS = "You are the technical specialist of a support team. Check the service status, then write two or three short notes for the team about the problem and how to get past it. Don't write to the customer."


