WRITE_REPLY_MESSAGE = """\
The customer wrote:
{request}

The team's notes:
Billing: {billing_note}
Technical: {technical_note}
Accounts: {accounts_note}

Write the reply."""

write_reply_template = ChatPromptTemplate.from_messages(
    [
        ("system", "You write replies for a customer support team. Be warm and brief, and only promise what the notes say was done."),
        ("human", WRITE_REPLY_MESSAGE),
    ]
)


def write_reply(data: FlowData) -> dict[str, Any]:
    """Instructions · Write the reply

    Fills in {request}, {billing_note}, {technical_note}, {accounts_note} and saves the prompt
    messages as `prompt`.
    """
    prompt = write_reply_template.invoke(
        {
            "request": data.get("request", ""),
            "billing_note": data.get("billing_note", ""),
            "technical_note": data.get("technical_note", ""),
            "accounts_note": data.get("accounts_note", ""),
        }
    )
    return {"prompt": prompt.to_messages()}


def reply(data: FlowData) -> dict[str, Any]:
    """AI Model · Reply

    Sends `prompt` to openai:gpt-4o-mini and saves the reply as `answer`.
    """
    model = init_chat_model("openai:gpt-4o-mini")
    reply = model.invoke(data["prompt"])
    return {"answer": reply.text}


# ── Flow ─────────────────────────────────────────────────────────────────────


def build_graph(checkpointer=None, *, store=None, cache=None):
    """Wire the steps into a LangGraph graph.

    Pass a checkpointer (for example InMemorySaver()) to keep a Save Point after every step,
    a store to remember side effects across retries, and a cache for cached steps.
    """
    builder = StateGraph(FlowData, input_schema=FlowInput, output_schema=FlowOutput)

    builder.add_node("supervisor", supervisor)
    builder.add_node("billing", billing)
    builder.add_node("technical", technical)
    builder.add_node("accounts", accounts)
    builder.add_node("write_reply", write_reply)
    builder.add_node("reply", reply)

    builder.add_edge(START, "supervisor")
    builder.add_conditional_edges(
        "supervisor",
        route_supervisor,
        {
            "Billing": "billing",
            "Technical": "technical",
            "Accounts": "accounts",
            "Finish": "write_reply",
        },
    )
    builder.add_edge("billing", "supervisor")
    builder.add_edge("technical", "supervisor")
    builder.add_edge("accounts", "supervisor")
    builder.add_edge("write_reply", "reply")
    builder.add_edge("reply", END)
    return builder.compile(checkpointer=checkpointer, store=store, cache=cache)


graph = build_graph()


if __name__ == "__main__":
    example = {"request": "I was charged twice this month, and now I can't sign in."}
    inputs = json.loads(sys.argv[1]) if len(sys.argv) > 1 else example
    result = graph.invoke({**ROUND_COUNTERS, **inputs})
    print(json.dumps(result, indent=2, ensure_ascii=False, default=str))
