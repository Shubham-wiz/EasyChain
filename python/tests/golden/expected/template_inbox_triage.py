# Code · Create a ticket (sets ticket, title, priority)
def create_ticket_code(data):
    """Open a ticket (a stand-in: it is only numbered; connect your helpdesk's API here)."""
    number = 1000 + zlib.crc32(data["title"].encode()) % 9000
    return {"ticket": f"T-{number}", "title": data["title"], "priority": data["priority"]}


def create_ticket(data: FlowData) -> dict[str, Any]:
    """Code · Create a ticket

    Runs create_ticket_code at most once: a retry or a resume after a crash reuses its first
    result.
    """
    return run_once(idempotency_key(), lambda: create_ticket_code(data))


def create_ticket_tool(data: FlowData) -> BaseTool:
    """Code “Create a ticket” as a tool for agents: create_ticket(priority, title)."""

    @tool(
        "create_ticket",
        description="Opens a ticket for the team and returns its number.",
    )
    def run_tool(
        priority: Annotated[str, "The ticket's priority: urgent, normal or low"],
        title: Annotated[str, "A one-line title for the ticket"],
    ) -> str:
        result = create_ticket({**data, "priority": priority, "title": title})
        return as_text(result.get("ticket"))

    return run_tool


def ticketer(data: FlowData) -> dict[str, Any]:
    """Agent · Open a ticket

    Works on `email` using openai:gpt-4o-mini and the tool create_ticket, and saves its answer
    as `ticket_note`.
    """
    agent = create_agent(
        model=init_chat_model("openai:gpt-4o-mini"),
        tools=[create_ticket_tool(data)],
        system_prompt=TICKETER_INSTRUCTIONS,
        middleware=[
            ToolCallLimitMiddleware(run_limit=1),
            ToolErrorMiddleware(tell_agent),
        ],
        name="ticketer",
    )
    result = agent.invoke(
        {"messages": [HumanMessage(str(data.get("email", "")))]}, {"recursion_limit": 12}
    )
    return {"ticket_note": result["messages"][-1].text}


def urgent(data: FlowData) -> dict[str, Any]:
    """Decision · Is it urgent?

    Changes no data; route_urgent below picks the exit.
    """
    return {}


def route_urgent(data: FlowData) -> str:
    """Pick the exit for the Decision "Is it urgent?"."""
    if str(data.get("urgency") or "").strip().lower() == "urgent":
        return "Urgent"
    return "Not urgent"


def check(data: FlowData) -> dict[str, Any]:
    """Ask a Human · Check the reply

    Pauses the run (a LangGraph interrupt) until a person edits `draft` and approves or rejects;
    saves the decision as `checked`.
    """
    answer = interrupt(
        {
            "step": "check",
            "kind": "edit",
            "question": "This email is urgent. Check the reply before it goes out.",
            "show": {"email": data.get("email"), "summary": data.get("summary"), "customer_note": data.get("customer_note"), "ticket_note": data.get("ticket_note")},
            "field": "draft",
            "value": data.get("draft"),
        }
    )
    if not isinstance(answer, dict):  # resumed with a bare value
        answer = {"value": answer}
    approved = answer.get("action", "approve") == "approve"
    update: dict[str, Any] = {
        "checked": "Approved" if approved else "Rejected",
        "checked_comment": str(answer.get("comment") or ""),
    }
    if approved and answer.get("value") is not None:
        update["draft"] = answer["value"]
    return update


def route_check(data: FlowData) -> str:
    """Follow the answer given at "Check the reply"."""
    return "Approved" if data.get("checked") == "Approved" else "Rejected"


