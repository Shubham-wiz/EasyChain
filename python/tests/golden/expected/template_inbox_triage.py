def build_graph(checkpointer=None, *, store=None, cache=None):
    """Wire the steps into a LangGraph graph.

    Pass a checkpointer (for example InMemorySaver()) to keep a Save Point after every step,
    a store to remember side effects across retries, and a cache for cached steps.
    """
    builder = StateGraph(FlowData, input_schema=FlowInput, output_schema=FlowOutput)

    builder.add_node("sort_prompt", sort_prompt)
    builder.add_node("sort", sort)
    builder.add_node("supervisor", supervisor)
    builder.add_node("lookup", lookup)
    builder.add_node("drafter", drafter)
    builder.add_node("ticketer", ticketer)
    builder.add_node("urgent", urgent)
    builder.add_node("check", check)

    builder.add_edge(START, "sort_prompt")
    builder.add_edge("sort_prompt", "sort")
    builder.add_edge("sort", "supervisor")
    builder.add_conditional_edges(
        "supervisor",
        route_supervisor,
        {
            "Look up the sender": "lookup",
            "Draft a reply": "drafter",
            "Open a ticket": "ticketer",
            "Done": "urgent",
        },
    )
    builder.add_edge("lookup", "supervisor")
    builder.add_edge("drafter", "supervisor")
    builder.add_edge("ticketer", "supervisor")
    builder.add_conditional_edges(
        "urgent",
        route_urgent,
        {
            "Urgent": "check",
            "Not urgent": END,
        },
    )
    builder.add_conditional_edges("check", route_check, {"Approved": END, "Rejected": END})
    return builder.compile(checkpointer=checkpointer, store=store, cache=cache)


