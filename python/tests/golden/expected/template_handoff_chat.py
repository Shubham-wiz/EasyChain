HAND_OFF_EXITS = ["Flights", "Hotels"]
HAND_OFF_GUIDANCE = """\
You route a travel agency's chat; the desk helping now is "{desk}" (empty is the front desk). Read its last reply and pick the desk that should help the traveller next. Pick Stay when the desk helping now should carry on, or the traveller has what they asked for.
Choose the exit that fits best. Reply with the exit name only.

Exits:
- Flights: the traveller wants to fly, or needs a flight or a plane ticket
- Hotels: the traveller needs a hotel, a room or somewhere to stay
- Stay: none of the above"""


def hand_off(data: FlowData) -> dict[str, Any]:
    """Decision · Hand over?

    Asks openai:gpt-4o-mini which exit fits `messages` and saves it as `next_desk`.
    """
    model = init_chat_model("openai:gpt-4o-mini", temperature=0)
    reply = model.invoke([("system", fill(HAND_OFF_GUIDANCE, data)), ("human", data["messages"][-1].text if data.get("messages") else "")])
    return {"next_desk": pick_exit(reply.text, HAND_OFF_EXITS, "Stay"), "hand_off_rounds": data.get("hand_off_rounds", 0) + 1}


def route_hand_off(data: FlowData) -> str:
    """Follow the exit the AI picked for "Hand over?"."""
    if data.get("hand_off_rounds", 0) >= 3:  # round limit reached
        return "Stay"
    return data.get("next_desk") or "Stay"


def to_flights(data: FlowData) -> Command:
    """Jump · To the flights desk

    Sets `switched`, `desk` (in order), then picks the next step.
    """
    data = {**data}  # later fields see the earlier ones
    data["switched"] = data.get("desk") != "flights"
    data["desk"] = "flights"
    update = {name: data[name] for name in ("switched", "desk")}
    if bool(data.get("switched")):
        return Command(update=update, goto="flights")
    return Command(update=update, goto=END)


def to_hotels(data: FlowData) -> Command:
    """Jump · To the hotels desk

    Sets `switched`, `desk` (in order), then picks the next step.
    """
    data = {**data}  # later fields see the earlier ones
    data["switched"] = data.get("desk") != "hotels"
    data["desk"] = "hotels"
    update = {name: data[name] for name in ("switched", "desk")}
    if bool(data.get("switched")):
        return Command(update=update, goto="hotels")
    return Command(update=update, goto=END)


# ── Flow ─────────────────────────────────────────────────────────────────────


def build_graph(checkpointer=None, *, store=None, cache=None):
    """Wire the steps into a LangGraph graph.

    Pass a checkpointer (for example InMemorySaver()) to keep a Save Point after every step,
    a store to remember side effects across retries, and a cache for cached steps.
    """
    builder = StateGraph(FlowData, input_schema=FlowInput, output_schema=FlowOutput)

    builder.add_node("route", route)
    builder.add_node("front_desk", front_desk)
    builder.add_node("flights", flights)
    builder.add_node("hotels", hotels)
    builder.add_node("hand_off", hand_off)
    builder.add_node("to_flights", to_flights, destinations=("flights", END))
    builder.add_node("to_hotels", to_hotels, destinations=("hotels", END))

    builder.add_edge(START, "route")
    builder.add_conditional_edges(
        "route",
        route_route,
        {
            "Flights": "flights",
            "Hotels": "hotels",
            "Front desk": "front_desk",
        },
    )
    builder.add_edge("front_desk", "hand_off")
    builder.add_edge("flights", "hand_off")
    builder.add_edge("hotels", "hand_off")
    builder.add_conditional_edges(
        "hand_off",
        route_hand_off,
        {
            "Flights": "to_flights",
            "Hotels": "to_hotels",
            "Stay": END,
        },
    )
    return builder.compile(checkpointer=checkpointer, store=store, cache=cache)


graph = build_graph()


if __name__ == "__main__":
    app = build_graph(checkpointer=InMemorySaver())
    config = {"configurable": {"thread_id": "terminal"}}
    # Chat in the terminal. Save Points keep the conversation between turns.
    while True:
        try:
            text = input("you> ").strip()
        except (EOFError, KeyboardInterrupt):
            break
        if text:
            result = app.invoke({**ROUND_COUNTERS, "messages": [{"role": "user", "content": text}]}, config)
            print("ai>", result["messages"][-1].text)
